"""Vicinae launcher theme. Only the keys set here are overridden; everything
else is inherited from the built-in vicinae-dark theme. Run
`vicinae theme template` for the full list of keys."""

OUT = "vicinae/.local/share/vicinae/themes/{slug}.toml"


def build(c):
    def q(value):
        return f'"{value}"'

    sections = {
        "meta": {
            "version": "1",
            "name": q(c.name),
            "description": q(f"{c.name}, generated from {c.source}"),
            "variant": q(c.variant),
        },
        "colors.core": {
            "background": q(c.base),
            "secondary_background": q(c.mantle),
            "foreground": q(c.text),
            "border": q(c.surface1),
            "accent": q(c.accent),
            "accent_foreground": q(c.base),
        },
        "colors.main_window": {
            "border": q(c.surface1),
        },
        "colors.settings_window": {
            "border": q(c.surface1),
        },
        "colors.accents": {
            "blue": q(c.hue.blue),
            "green": q(c.hue.green),
            "magenta": q(c.hue.pink),
            "orange": q(c.hue.orange),
            "purple": q(c.hue.purple),
            "red": q(c.hue.red),
            "yellow": q(c.hue.yellow),
            "cyan": q(c.hue.cyan),
        },
        "colors.text": {
            "muted": q(c.subtext0),
            "placeholder": q(c.overlay0),
            "danger": q(c.error),
            "success": q(c.marker),
            "selection": f"{{ background = {q(c.surface2)}, foreground = {q(c.text)} }}",
        },
        "colors.text.links": {
            "default": q(c.link),
            "visited": q(c.visited),
        },
        "colors.input": {
            "border": q(c.surface1),
            "border_focus": q(c.accent),
            "border_error": q(c.error),
        },
        "colors.button.primary": {
            "background": q(c.surface0),
            "foreground": q(c.text),
            "hover": f"{{ background = {q(c.surface1)} }}",
            "focus": f"{{ outline = {q(c.accent)} }}",
        },
        "colors.list.item.hover": {
            "foreground": q(c.text),
            "secondary_foreground": q(c.subtext1),
        },
        "colors.list.item.selection": {
            "background": q(c.surface0),
            "foreground": q(c.bright),
            "secondary_background": q(c.surface1),
            "secondary_foreground": q(c.subtext1),
        },
        "colors.grid.item": {
            "background": q(c.surface0),
            "hover": f"{{ outline = {q(c.overlay1)} }}",
            "selection": f"{{ outline = {q(c.accent)} }}",
        },
        "colors.scrollbars": {
            "background": q(c.surface2),
        },
        "colors.loading": {
            "bar": q(c.marker),
            "spinner": q(c.text),
        },
    }

    lines = [
        f"# {c.name}",
        f"# Generated by theming/generate.py from {c.source}.",
        "# Edit those, not this file.",
    ]
    for section, keys in sections.items():
        lines += ["", f"[{section}]"]
        lines += [f"{key} = {value}" for key, value in keys.items()]
    return {OUT.format(slug=c.slug): "\n".join(lines) + "\n"}
